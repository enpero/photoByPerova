const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('docs/index.html', 'utf8');
assert(!html.includes('data-device-view'));
assert(!html.includes('device-switch'));
assert(!html.includes('html[data-device='));
assert(html.includes('content="width=device-width, initial-scale=1, viewport-fit=cover"'));
assert(html.includes('@container page (max-width: 767px)'));
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
let stored = 'desktop';
vm.runInNewContext(script, { localStorage: { removeItem(key) { assert.equal(key, 'perova-device-view'); stored = null; } } });
assert.equal(stored, null);
assert.doesNotThrow(() => vm.runInNewContext(script, { localStorage: { removeItem() { throw Error('Storage unavailable'); } } }));
console.log('Passed: automatic responsive layout, manual controls removed, old preference cleared, unavailable storage handled.');
